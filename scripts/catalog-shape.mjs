/**
 * Shared catalog-introspection helpers for the bootstrap proof (CAP-1).
 *
 * Two callers need the same answer to "what schema does this database have?":
 *
 *   - scripts/verify-multi-instance.mjs compares a concurrently-booted database
 *     against a single-boot reference;
 *   - tests/matrix/bmad-bootstrap.spec.ts asserts a replayed `ensureSchema()`
 *     leaves the catalog byte-identical.
 *
 * They used to carry the same SQL verbatim, which is the shape that drifts:
 * a fix to one comparison silently leaves the other weaker. This module is the
 * one definition. It is deliberately query-only — it creates nothing, drops
 * nothing, and does not know about scratch-database lifecycles
 * (scripts/test-db.mjs owns those).
 *
 * No `import.meta`: like test-db.mjs, this module must stay importable from
 * contexts that transpile to CommonJS.
 */
import pg from "pg";

/**
 * Floor for a full bootstrap's catalog dump.
 *
 * A dump that captured nothing would be identical to another dump that captured
 * nothing, so "the two shapes match" and "the shape did not change" must never
 * be satisfiable by an empty result. The full v2→v9 catalog is 381 rows on the
 * current schema; the floor is well below that so adding a table does not
 * require touching this number, while an empty or partial dump still fails.
 */
export const MIN_CATALOG_ROWS = 300;

/**
 * Every table, column, constraint and index in `public`, one sorted line each.
 *
 * OIDs are deliberately excluded: they differ between any two databases by
 * construction, while definitions are what "the same schema" means. Sorted so
 * two matching databases produce identical arrays.
 */
export async function readCatalogShape(connectionString) {
  const client = new pg.Client({ connectionString });
  await client.connect();
  try {
    const { rows } = await client.query(`
      SELECT kind, name, detail FROM (
        SELECT 'table' AS kind, c.relname AS name, '' AS detail
          FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
         WHERE n.nspname = 'public' AND c.relkind = 'r'
        UNION ALL
        SELECT 'column', table_name || '.' || column_name,
               data_type || ' null=' || is_nullable ||
               ' default=' || coalesce(column_default, '')
          FROM information_schema.columns
         WHERE table_schema = 'public'
        UNION ALL
        SELECT 'constraint', conrelid::regclass::text || '.' || conname,
               pg_get_constraintdef(oid)
          FROM pg_constraint
         WHERE connamespace = 'public'::regnamespace
        UNION ALL
        SELECT 'index', schemaname || '.' || indexname, indexdef
          FROM pg_indexes
         WHERE schemaname = 'public'
      ) catalog
      ORDER BY kind, name, detail
    `);
    return rows.map((row) => `${row.kind}\t${row.name}\t${row.detail}`);
  } finally {
    await client.end().catch(() => {});
  }
}

/** Line-by-line difference between two catalog dumps; empty means identical. */
export function diffCatalogShapes(reference, actual) {
  const expected = new Set(reference);
  const found = new Set(actual);
  return [
    ...reference
      .filter((line) => !found.has(line))
      .map((line) => `missing: ${line}`),
    ...actual
      .filter((line) => !expected.has(line))
      .map((line) => `unexpected: ${line}`),
  ];
}

/**
 * Row count per relation, keyed by table name. Used to catch what a schema
 * comparison cannot: a seed row duplicated or lost under concurrent boots.
 * Relation names are generated by the caller, but they are still quoted as
 * identifiers so a stray name can never be read as SQL.
 */
export async function readRelationRowCounts(connectionString, relations) {
  const client = new pg.Client({ connectionString });
  await client.connect();
  try {
    const counts = {};
    for (const relation of relations) {
      const identifier = `"${relation.replaceAll('"', '""')}"`;
      const { rows } = await client.query(
        `SELECT count(*)::int AS count FROM ${identifier}`
      );
      counts[relation] = Number(rows[0]?.count ?? 0);
    }
    return counts;
  } finally {
    await client.end().catch(() => {});
  }
}
